def _decode(payload: str) -> np.ndarray:
    raw = zlib.decompress(base64.b64decode(payload.encode("ascii")))
    data = np.frombuffer(raw, dtype=np.uint8)
    image = cv2.imdecode(data, cv2.IMREAD_GRAYSCALE)
    if image is None:
        raise ValueError("内嵌箭头模板解码失败")
    return image


def load_gray(name: str) -> np.ndarray:
    """按文件名（expand_down.png / expand_up.png）返回灰度模板。"""
    key = str(name).replace("\\", "/").rsplit("/", 1)[-1].lower()
    if "down" in key:
        return _decode(_DOWN_B64)
    if "up" in key:
        return _decode(_UP_B64)
    raise KeyError(f"未知模板: {name}")
